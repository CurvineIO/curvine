//! Unified configuration loading pipeline.
//!
//! Layer order (low → high priority):
//!
//! ```text
//! serde defaults → file (TOML) → environment (explicit allowlist) → CLI overrides (typed)
//! ```
//!
//! The file and environment layers are merged as raw `toml::Value` documents and
//! deserialized exactly once into [`ClusterConf`], so native serde semantics
//! (`#[serde(default)]`, aliases, arrays of tables, error messages) are preserved
//! without an intermediate value model. Typed CLI overrides (generated by the
//! `ClientCliArgs` derive macro) run after deserialization and therefore sit on
//! top of the whole stack; a future runtime/admin overlay will slot between the
//! environment layer and deserialization without changing this module's shape.
//!
//! Environment variables are applied through an explicit allowlist table
//! ([`ENV_HOSTNAME_OVERRIDES`]) instead of generic name→path mapping: Curvine key
//! names are underscore-heavy (`format_master`, `master_addrs`, …), which makes
//! separator-based automatic mapping ambiguous. Adding a new env override is one
//! new row in the table plus a unit test.

use crate::ClusterConf;
use curvine_core_error::{err_box, try_err, CommonResult};
use std::env;
use std::fs::read_to_string;
use std::path::PathBuf;

/// Which entrypoint is loading the configuration. Controls how much of the env
/// layer applies, mirroring the historical `from()` / `from_transfer()` split.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LoadProfile {
    /// master / worker / fuse / cli / sdk: all sections participate.
    Full,
    /// Standalone transfer service: only client + transfer hostnames resolve.
    Transfer,
}

/// One allowlisted environment variable and the dotted config paths it feeds.
#[derive(Debug, Clone, Copy)]
pub struct EnvOverride {
    pub var: &'static str,
    /// Dotted paths into the cluster TOML document (e.g. `"worker.hostname"`).
    /// One variable may feed several paths (master hostname also seeds journal).
    pub paths: &'static [&'static str],
}

/// Hostname-related env allowlist. Applied only when `net_interface` is unset
/// (see [`apply_env_layer`]); values are trimmed before use, matching the
/// historical behavior.
pub const ENV_HOSTNAME_OVERRIDES: &[EnvOverride] = &[
    EnvOverride {
        var: ClusterConf::ENV_MASTER_HOSTNAME,
        paths: &["master.hostname", "journal.hostname"],
    },
    EnvOverride {
        var: ClusterConf::ENV_WORKER_HOSTNAME,
        paths: &["worker.hostname"],
    },
    EnvOverride {
        var: ClusterConf::ENV_CLIENT_HOSTNAME,
        paths: &["client.hostname"],
    },
    EnvOverride {
        var: ClusterConf::ENV_TRANSFER_HOSTNAME,
        paths: &["transfer.hostname"],
    },
];

/// Document key holding the NIC used to auto-resolve local IPv4 hostnames.
const NET_INTERFACE_KEY: &str = "net_interface";

// ---------------------------------------------------------------------------
// Document assembly
// ---------------------------------------------------------------------------

/// Reads the raw TOML text of a config file.
pub fn read_file_text<T: AsRef<str>>(path: T) -> CommonResult<String> {
    let path = path.as_ref();
    let text = try_err!(read_to_string(path));
    Ok(text)
}

/// Builds the effective pre-deserialization document:
/// file TOML → deep-merge overlays → environment layer.
///
/// `overlays` are applied in order, each on top of the previous result
/// (reserved for future formats / runtime overlay layers).
pub fn build_document(file_text: &str, overlays: &[toml::Value]) -> CommonResult<toml::Value> {
    let mut doc: toml::Value = try_err!(toml::from_str(file_text));
    for overlay in overlays {
        deep_merge(&mut doc, overlay);
    }
    apply_env_layer_with(&mut doc, LoadProfile::Full, &real_env_lookup)?;
    Ok(doc)
}

/// [`build_document`] restricted to the transfer service's hostname scope.
pub fn build_transfer_document(
    file_text: &str,
    overlays: &[toml::Value],
) -> CommonResult<toml::Value> {
    let mut doc: toml::Value = try_err!(toml::from_str(file_text));
    for overlay in overlays {
        deep_merge(&mut doc, overlay);
    }
    apply_env_layer_with(&mut doc, LoadProfile::Transfer, &real_env_lookup)?;
    Ok(doc)
}

/// Production environment lookup.
fn real_env_lookup(var: &str) -> Option<String> {
    env::var(var).ok()
}

/// Environment layer: net_interface resolution + `CURVINE_*_HOSTNAME` overrides.
///
/// Behavior ported 1:1 from the pre-pipeline loader:
/// - A non-empty (trimmed) `net_interface` in the document wins: its local IPv4
///   replaces every role hostname, any set hostname env vars are ignored with a
///   stderr warning (logger is not initialized yet at load time).
/// - Otherwise each set env var from [`ENV_HOSTNAME_OVERRIDES`] (trimmed) is
///   written to its dotted paths.
pub fn apply_env_layer_with(
    doc: &mut toml::Value,
    profile: LoadProfile,
    lookup: &dyn Fn(&str) -> Option<String>,
) -> CommonResult<()> {
    let scoped: Vec<&EnvOverride> = ENV_HOSTNAME_OVERRIDES
        .iter()
        .filter(|o| match profile {
            LoadProfile::Full => true,
            // The standalone transfer process only resolves its own hostname
            // (plus the client it embeds); touching master/journal/worker
            // entries would be surprising for a data-plane-only service.
            LoadProfile::Transfer => {
                o.var == ClusterConf::ENV_CLIENT_HOSTNAME
                    || o.var == ClusterConf::ENV_TRANSFER_HOSTNAME
            }
        })
        .collect();

    if net_interface_set(doc) {
        let interface = doc_string(doc, &[NET_INTERFACE_KEY])
            .unwrap_or_default()
            .trim()
            .to_string();
        let ip = ClusterConf::interface_ipv4(&interface)?;

        // net_interface takes precedence over the CURVINE_*_HOSTNAME env vars.
        // Warn (rather than silently ignore) when any of them is also set, so
        // an operator who exported a hostname override but sees it have no
        // effect can tell why. Runs before Logger::init — use eprintln!.
        let mut touched = Vec::new();
        for entry in &scoped {
            if lookup(entry.var).is_some() {
                eprintln!(
                    "[WARN] net_interface '{}' is set (resolved to {}); ignoring {}.",
                    interface, ip, entry.var
                );
            }
            // The NIC-resolved IP replaces every path the profile's allowlist
            // entries feed — same addressing as the env-value branch below,
            // so there is exactly one source of truth for the scope.
            for path in entry.paths {
                touched.push(*path);
            }
        }
        for path in touched {
            set_dotted(doc, path, toml::Value::String(ip.clone()))?;
        }
        return Ok(());
    }

    for entry in scoped {
        if let Some(value) = lookup(entry.var) {
            let value = value.trim().to_string();
            for path in entry.paths {
                set_dotted(doc, path, toml::Value::String(value.clone()))?;
            }
        }
    }
    Ok(())
}

fn net_interface_set(doc: &toml::Value) -> bool {
    doc_string(doc, &[NET_INTERFACE_KEY])
        .map(|v| !v.trim().is_empty())
        .unwrap_or(false)
}

// ---------------------------------------------------------------------------
// toml::Value navigation helpers
// ---------------------------------------------------------------------------

/// Reads a string at a dotted path; `None` when any segment is missing or the
/// leaf is not a string.
pub fn doc_string(doc: &toml::Value, path: &[&str]) -> Option<String> {
    let mut cur = doc;
    for seg in path {
        cur = cur.get(seg)?;
    }
    cur.as_str().map(str::to_string)
}

/// Sets a value at a dotted path, creating intermediate tables as needed.
pub fn set_dotted(doc: &mut toml::Value, path: &str, value: toml::Value) -> CommonResult<()> {
    let segments: Vec<&str> = path.split('.').collect();
    if segments.is_empty() {
        return err_box!("empty config path");
    }
    let mut cur = doc;
    for seg in &segments[..segments.len() - 1] {
        if !cur.is_table() {
            return err_box!(
                "config path '{}' collides with a non-table value at '{}'",
                path,
                seg
            );
        }
        let table = cur.as_table_mut().expect("checked is_table");
        cur = table
            .entry(seg.to_string())
            .or_insert_with(|| toml::Value::Table(toml::value::Table::new()));
    }
    let last = segments[segments.len() - 1];
    if !cur.is_table() {
        return err_box!("config path '{}' parent is not a table", path);
    }
    cur.as_table_mut()
        .expect("checked is_table")
        .insert(last.to_string(), value);
    Ok(())
}

/// Deep-merges `overlay` into `base`: tables merge recursively, scalars and
/// arrays are replaced wholesale (arrays never merge element-wise — a list is
/// one configuration value).
pub fn deep_merge(base: &mut toml::Value, overlay: &toml::Value) {
    match (base, overlay) {
        (toml::Value::Table(base_t), toml::Value::Table(overlay_t)) => {
            for (key, overlay_v) in overlay_t {
                match base_t.get_mut(key) {
                    Some(base_v) if base_v.is_table() && overlay_v.is_table() => {
                        deep_merge(base_v, overlay_v);
                    }
                    _ => {
                        base_t.insert(key.clone(), overlay_v.clone());
                    }
                }
            }
        }
        (base, overlay) => *base = overlay.clone(),
    }
}

