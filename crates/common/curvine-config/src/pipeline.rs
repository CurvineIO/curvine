/// A located config file path plus a human-readable source label for logs.
#[derive(Debug, Clone)]
pub struct DiscoveredPath {
    pub path: PathBuf,
    pub source: String,
}

impl DiscoveredPath {
    pub fn as_str(&self) -> std::borrow::Cow<'_, str> {
        self.path.to_string_lossy()
    }
}

/// Unified config-file discovery shared by every component entrypoint
/// (server / fuse / cli / sdk / lancedb), replacing per-crate duplicates.
pub struct ConfigLoader;

impl ConfigLoader {
    pub const DEFAULT_FILE_NAME: &'static str = "curvine-cluster.toml";

    /// Discovery order:
    /// 1. explicit path (CLI `--conf`, storage option, …), taken as-is even if
    ///    missing — the subsequent load produces the actionable error;
    /// 2. `CURVINE_CONF_FILE`;
    /// 3. well-known locations ([`Self::default_candidates`]), first that exists.
    ///
    /// Returns `None` only when nothing was configured or found; callers decide
    /// their own fallback policy (error out vs. run on defaults).
    pub fn discover(explicit: Option<&str>) -> Option<DiscoveredPath> {
        Self::discover_configured(explicit).or_else(|| {
            Self::default_candidates()
                .into_iter()
                .find(|(path, _)| path.exists())
                .map(|(path, source)| DiscoveredPath {
                    path,
                    source: source.to_string(),
                })
        })
    }

    /// Discovery restricted to explicitly configured sources (argument or
    /// `CURVINE_CONF_FILE`), without probing default locations. For embedders
    /// (e.g. lancedb) whose own fallback chain must run before any
    /// filesystem probing would be appropriate.
    pub fn discover_configured(explicit: Option<&str>) -> Option<DiscoveredPath> {
        if let Some(path) = explicit.map(str::trim).filter(|p| !p.is_empty()) {
            return Some(DiscoveredPath {
                path: PathBuf::from(path),
                source: "--conf".to_string(),
            });
        }

        if let Ok(path) = env::var(ClusterConf::ENV_CONF_FILE) {
            return Some(DiscoveredPath {
                path: PathBuf::from(path),
                source: ClusterConf::ENV_CONF_FILE.to_string(),
            });
        }

        None
    }

    /// Well-known fallback locations in probe order.
    pub fn default_candidates() -> Vec<(PathBuf, &'static str)> {
        let mut candidates = vec![
            (PathBuf::from(Self::DEFAULT_FILE_NAME), "current directory"),
            (
                PathBuf::from("conf").join(Self::DEFAULT_FILE_NAME),
                "current conf directory",
            ),
        ];

        if let Some(home) = env::var_os("HOME") {
            candidates.push((
                PathBuf::from(home)
                    .join(".curvine")
                    .join(Self::DEFAULT_FILE_NAME),
                "user config directory",
            ));
        }

        if let Ok(curvine_home) = env::var("CURVINE_HOME") {
            candidates.push((
                PathBuf::from(curvine_home)
                    .join("conf")
                    .join(Self::DEFAULT_FILE_NAME),
                "CURVINE_HOME",
            ));
        }

        candidates
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn lookup<'a>(map: &'a [(&'a str, &'a str)]) -> impl Fn(&str) -> Option<String> + 'a {
        let map: HashMap<String, String> = map
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect();
        move |var| map.get(var).cloned()
    }

    #[test]
    fn deep_merge_replaces_scalars_and_merges_tables() {
        let base_text = r#"
            [master]
            hostname = "a"
            rpc_port = 1
        "#;
        let mut base: toml::Value = toml::from_str(base_text).unwrap();
        let overlay: toml::Value = toml::from_str(
            r#"
            format_master = true
            [master]
            hostname = "b"
            [client]
            io_threads = 4
            "#,
        )
        .unwrap();

        deep_merge(&mut base, &overlay);

        assert_eq!(base["format_master"].as_bool(), Some(true));
        assert_eq!(base["master"]["hostname"].as_str(), Some("b"));
        assert_eq!(base["master"]["rpc_port"].as_integer(), Some(1));
        assert_eq!(base["client"]["io_threads"].as_integer(), Some(4));
    }

    #[test]
    fn deep_merge_replaces_arrays_wholesale() {
        let mut base: toml::Value = toml::from_str("a = [1, 2, 3]").unwrap();
        let overlay: toml::Value = toml::from_str("a = [9]").unwrap();
        deep_merge(&mut base, &overlay);
        assert_eq!(base["a"].as_array().unwrap().len(), 1);
    }

    #[test]
    fn set_and_get_dotted_paths() {
        let mut doc = toml::Value::Table(toml::value::Table::new());
        set_dotted(&mut doc, "master.hostname", toml::Value::String("h".into())).unwrap();

        assert_eq!(doc_string(&doc, &["master", "hostname"]), Some("h".into()));
        assert_eq!(doc_string(&doc, &["master", "missing"]), None);

        // Overwrite an existing nested value.
        set_dotted(
            &mut doc,
            "master.hostname",
            toml::Value::String("h2".into()),
        )
        .unwrap();
        assert_eq!(doc_string(&doc, &["master", "hostname"]), Some("h2".into()));
    }

    #[test]
    fn env_hostname_overrides_apply_trimmed_values() {
        let mut doc: toml::Value = toml::from_str("[master]\nhostname = \"file\"\n").unwrap();
        let env = lookup(&[
            (ClusterConf::ENV_MASTER_HOSTNAME, " master-01 "),
            (ClusterConf::ENV_WORKER_HOSTNAME, "worker-01"),
        ]);
        apply_env_layer_with(&mut doc, LoadProfile::Full, &env).unwrap();

        // Master hostname seeds both master and journal sections.
        assert_eq!(
            doc_string(&doc, &["master", "hostname"]),
            Some("master-01".into())
        );
        assert_eq!(
            doc_string(&doc, &["journal", "hostname"]),
            Some("master-01".into())
        );
        assert_eq!(
            doc_string(&doc, &["worker", "hostname"]),
            Some("worker-01".into())
        );
        // Unset vars leave file values untouched.
        assert!(doc.get("client").is_none());
    }

    #[test]
    fn transfer_profile_ignores_master_worker_env_vars() {
        let mut doc: toml::Value = toml::from_str("[master]\nhostname = \"file\"\n").unwrap();
        let env = lookup(&[
            (ClusterConf::ENV_MASTER_HOSTNAME, "ignored"),
            (ClusterConf::ENV_CLIENT_HOSTNAME, "client-01"),
        ]);
        apply_env_layer_with(&mut doc, LoadProfile::Transfer, &env).unwrap();

        assert_eq!(
            doc_string(&doc, &["master", "hostname"]),
            Some("file".into())
        );
        assert_eq!(
            doc_string(&doc, &["client", "hostname"]),
            Some("client-01".into())
        );
    }

    #[test]
    fn whitespace_only_net_interface_falls_back_to_env() {
        let mut doc: toml::Value = toml::from_str("net_interface = \" \"").unwrap();
        let env = lookup(&[(ClusterConf::ENV_WORKER_HOSTNAME, "worker-01")]);
        apply_env_layer_with(&mut doc, LoadProfile::Full, &env).unwrap();

        assert_eq!(
            doc_string(&doc, &["worker", "hostname"]),
            Some("worker-01".into())
        );
    }

    #[test]
    fn build_document_parses_file_and_applies_env() {
        let text = r#"
            [master]
            hostname = "file-master"

            [client]
            hostname = "file-client"
        "#;
        let env_map = lookup(&[(ClusterConf::ENV_MASTER_HOSTNAME, "env-master")]);
        // build_document uses real env; emulate by calling the stages directly.
        let mut doc: toml::Value = toml::from_str(text).unwrap();
        apply_env_layer_with(&mut doc, LoadProfile::Full, &env_map).unwrap();

        assert_eq!(
            doc_string(&doc, &["master", "hostname"]),
            Some("env-master".into())
        );
        assert_eq!(
            doc_string(&doc, &["client", "hostname"]),
            Some("file-client".into())
        );
    }

    #[test]
    fn discovery_prefers_explicit_over_env_var() {
        // Explicit path wins even when CURVINE_CONF_FILE is set; both are taken
        // as-is regardless of existence (load errors surface later with context).
        // We cannot safely mutate global env in parallel tests, so we exercise
        // only the explicit branch here; env/default branches share the same
        // code path verified by construction.
        let found = ConfigLoader::discover(Some("/tmp/explicit.toml")).unwrap();
        assert_eq!(found.source, "--conf");
        assert_eq!(found.as_str(), "/tmp/explicit.toml");
    }

    #[test]
    fn default_candidates_cover_well_known_locations() {
        let names: Vec<String> = ConfigLoader::default_candidates()
            .into_iter()
            .map(|(p, _)| p.file_name().unwrap().to_string_lossy().to_string())
            .collect();
        assert!(names.iter().all(|n| n == ConfigLoader::DEFAULT_FILE_NAME));
    }
}
