//! Chaos test: 40 concurrent writers/readers while random masters are SIGKILLed.
//!
//! After the run every node is restarted once (so each one rebuilds its derived
//! metadata store from journal + snapshot), then the test checks:
//! - file contents read back from the cluster, unique inode ids, and no ghost
//!   paths that no writer recorded;
//! - replay warnings/errors in the master logs;
//! - each master's offline `sum_hash` after replaying its own journal.
//!
//! Marked ignored because it spawns real processes, kills them, and takes a
//! couple of minutes. Run with:
//!   cargo test -p curvine-server --test chaos_metadata_test -- --ignored --nocapture

